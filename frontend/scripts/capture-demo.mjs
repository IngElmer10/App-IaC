import { chromium } from '@playwright/test';
import { mkdir, readFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const output = resolve('../.runtime/evidence');
await mkdir(output, { recursive: true });
const access = JSON.parse(await readFile(resolve('../.runtime/demo-access.json'), 'utf8'));
const session = await (await fetch('http://localhost:3001/api/auth/login', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ username: 'platform', password: process.env.PLATFORM_ADMIN_PASSWORD }) })).json();
const overview = await (await fetch('http://localhost:3001/api/platform/overview', { headers: { Authorization: `Bearer ${session.accessToken}` } })).json();
const tenant = overview.tenants.find((item) => item.slug === 'andina-demo');
const credentials = access.find((item) => item.id === tenant.id);
const browser = await chromium.launch();
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  await page.goto('http://localhost:3000');
  await page.getByRole('heading', { name: 'Básico', exact: true }).waitFor();
  await page.screenshot({ path: resolve(output, 'pagina-publica.png'), fullPage: true });
  await page.goto('http://localhost:3000/login');
  await page.getByRole('button', { name: 'Plataforma', exact: true }).click();
  await page.getByLabel('Contraseña', { exact: true }).fill(process.env.PLATFORM_ADMIN_PASSWORD);
  await page.getByRole('button', { name: 'Entrar al sistema' }).click();
  await page.getByRole('heading', { name: 'Plataforma de instituciones' }).waitFor();
  await page.getByRole('heading', { name: 'Universidad Andina', exact: true }).waitFor();
  await page.screenshot({ path: resolve(output, 'plataforma.png'), fullPage: true });
  await page.getByRole('button', { name: /Solicitudes \(/ }).click();
  await page.screenshot({ path: resolve(output, 'solicitudes.png'), fullPage: true });
  await page.getByRole('button', { name: 'Instituciones', exact: true }).click();
  await page.getByRole('heading', { name: 'Universidad Andina', exact: true }).click();
  await page.getByRole('heading', { name: 'Infraestructura de andina-demo', exact: true }).waitFor();
  await page.screenshot({ path: resolve(output, 'tres-instancias.png'), fullPage: true });
  await page.goto(tenant.publicUrl);
  await page.getByRole('button', { name: 'Administrador', exact: true }).click();
  await page.getByLabel('Contraseña', { exact: true }).fill(credentials.adminPassword);
  await page.getByRole('button', { name: 'Entrar al sistema' }).click();
  await page.getByRole('heading', { name: 'Dashboard', exact: true }).waitFor();
  await page.screenshot({ path: resolve(output, 'asistencia-aws.png'), fullPage: true });
  await page.goto(`${tenant.publicUrl}/grafana/login`);
  await page.locator('input[name="user"]').fill('admin');
  await page.locator('input[name="password"]').fill(credentials.adminPassword);
  await page.getByRole('button', { name: 'Log in', exact: true }).click();
  await page.waitForURL((url) => !url.pathname.endsWith('/login'));
  const queries = page.waitForResponse((response) => response.url().includes('/api/ds/query') && response.ok());
  await page.goto(`${tenant.publicUrl}/grafana/d/attendance-tenant`);
  await page.getByText('CPU por instancia (%)', { exact: true }).waitFor();
  const queryResult = await (await queries).json();
  if (!Object.values(queryResult.results || {}).some((result) => result.frames?.length > 0)) throw new Error('Grafana no devolvió series de métricas.');
  await page.getByRole('button', { name: 'Cancel', exact: true }).waitFor({ state: 'hidden' });
  await page.screenshot({ path: resolve(output, 'grafana-aws.png'), fullPage: true });
  const studentPage = await browser.newPage({ viewport: { width: 390, height: 844 } });
  await studentPage.goto(tenant.publicUrl);
  await studentPage.getByRole('button', { name: 'Estudiante', exact: true }).click();
  await studentPage.getByLabel('Usuario', { exact: true }).fill('1001');
  await studentPage.getByLabel('Contraseña', { exact: true }).fill(credentials.studentPassword);
  await studentPage.getByRole('button', { name: 'Entrar al sistema' }).click();
  await studentPage.getByRole('heading', { name: 'Ana Andina', exact: true }).waitFor();
  await studentPage.getByRole('heading', { name: 'Historial de asistencia' }).waitFor();
  await studentPage.screenshot({ path: resolve(output, 'estudiante-movil-aws.png'), fullPage: true });
  console.log('Verificación visual completada: plataforma, aplicación en AWS y dashboard real de Grafana.');
  console.log('Capturas guardadas en .runtime/evidence/.');
} finally { await browser.close(); }
